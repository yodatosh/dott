#!/usr/bin/env python3
"""Generate the bundled RDAP directory from a downloaded IANA dns.json (offline)."""
import argparse
import json
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]


def generate(data):
    groups, seen = [], set()
    for tlds, urls in data['services']:
        candidates = []
        for url in urls:
            parsed = urlsplit(url)
            if (parsed.scheme not in ('https', 'http') or not parsed.hostname
                    or parsed.username or parsed.password or parsed.query or parsed.fragment):
                raise ValueError(f'Invalid RDAP base URL: {url!r}')
            candidates.append(url.rstrip('/') + '/')
        if not candidates or not tlds:
            raise ValueError('Empty RDAP service')
        base = next((url for url in candidates if url.startswith('https://')), candidates[0])
        names = sorted(tlds)
        for tld in names:
            if (not tld or len(tld) > 63 or not tld.isascii()
                    or any(c not in 'abcdefghijklmnopqrstuvwxyz0123456789-' for c in tld)
                    or tld.startswith('-') or tld.endswith('-') or tld in seen):
                raise ValueError(f'Invalid or duplicate TLD: {tld!r}')
            seen.add(tld)
        groups.append((names, base))
    if not groups:
        raise ValueError('Empty RDAP directory')
    lines = ['// Generated by Tools/update_rdap_bootstrap.py; do not edit.',
             '// Source: https://data.iana.org/rdap/dns.json',
             f'// IANA publication: {data["publication"]}',
             'pub const SERVICES: &[(&[&str], &str)] = &[']
    for names, base in sorted(groups):
        lines.append(f'    (&[{", ".join(json.dumps(t) for t in names)}], {json.dumps(base)}),')
    lines.extend(['];', '', 'pub fn base_url(tld: &str) -> Option<&\'static str> {',
                  '    SERVICES.iter().find(|(tlds, _)| tlds.contains(&tld)).map(|(_, base)| *base)', '}', ''])
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', required=True, type=Path)
    parser.add_argument('--output', type=Path, default=ROOT / 'src/rdap_bootstrap.rs')
    args = parser.parse_args()
    args.output.write_text(generate(json.loads(args.input.read_text())))


if __name__ == '__main__':
    main()
